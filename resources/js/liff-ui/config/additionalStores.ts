function membershipCard(primary: string, accent: string, textColor = "#ffffff"): MembershipCardConfig {
  return {
    templateId: "standard",
    backgroundType: "gradient",
    gradientFrom: primary,
    gradientTo: accent,
    textColor,
    logoVisible: true,
    memberNameVisible: true,
    memberNumberVisible: true,
    rankVisible: true,
    pointVisible: true,
    barcodeVisible: true,
    borderRadius: 26,
    shadow: "large",
  };
}

function tabs(items: Array<[TabConfig["type"], string]>): TabConfig[] {
  return items.map(([type, label], index) => ({ id: `${type}-${index}`, type, label, enabled: true, order: index + 1 }));
}

function actions(items: Array<[QuickAction["feature"], string, string]>): QuickAction[] {
  return items.map(([feature, label, icon], index) => ({ id: `qa-${feature}-${index}`, feature, label, icon, order: index + 1 }));
}

